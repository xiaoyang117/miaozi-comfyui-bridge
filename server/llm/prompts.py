# 把历史对话压成一段上下文，避免直接塞多轮消息让本地小模型跑偏
HISTORY_WRAPPER = (
    "以下是之前的对话记录，仅供你理解用户偏好和延续性，"
    "不要直接复述它们：\n{history}\n\n"
    "用户当前需求：{current}"
)


def build_history_text(pairs: list) -> str:
    """把 (用户输入, 助手提示词) 列表拼成一段简洁上下文。"""
    lines = []
    for user, assistant in pairs:
        lines.append(f"用户: {user}")
        if assistant:
            # 提示词可能很长，截断一下，避免本地小模型上下文炸掉
            lines.append(f"你上次生成的提示词: {assistant[:400]}")
    return "\n".join(lines)
